#include <iostream>
using namespace std;

int main() {
    float a, b;
    cout << "Enter first number:";
    cin >> a;

    cout << "Enter second number:";
    cin >> b;

    cout << "sum = " << a + b << endl;
    cout << "difference = " << a - b << endl;
    cout << "product = " << a * b << endl;
    cout << "quotient = " << a / b << endl;

    return 0;
}